def get_learning_resources(career, missing_skills=None):
    """
    Return learning resources relevant to the recommended career.

    Missing skills are prioritized first.
    """

    roadmap_skills = []

    if missing_skills:
        for item in missing_skills:
            if isinstance(item, dict):
                skill = item.get("skill")
            else:
                skill = str(item)

            if skill:
                roadmap_skills.append(skill)

    # Add common skills for the selected career.
    career_skills = {
        "Data Analyst": [
            "SQL",
            "Python",
            "Data Analysis",
            "Statistics"
        ],
        "Data Scientist": [
            "Python",
            "Statistics",
            "Machine Learning",
            "Data Analysis"
        ],
        "AI/ML Engineer": [
            "Python",
            "Machine Learning",
            "Artificial Intelligence",
            "Statistics"
        ],
        "Web Developer": [
            "HTML/CSS",
            "JavaScript",
            "Web Development",
            "Programming"
        ],
        "Software Developer": [
            "Programming",
            "Software Development",
            "Database",
            "Problem Solving"
        ],
        "Cybersecurity Analyst": [
            "Cybersecurity",
            "Networking",
            "Security Analysis",
            "Python"
        ],
        "Cloud Engineer": [
            "Cloud Computing",
            "Linux",
            "Networking",
            "Programming"
        ],
        "UI/UX Designer": [
            "UI Design",
            "UX Design",
            "Creativity",
            "Communication"
        ]
    }

    for skill in career_skills.get(career, []):
        if skill not in roadmap_skills:
            roadmap_skills.append(skill)

    resources = []

    for skill in roadmap_skills:

        skill_resources = LEARNING_RESOURCES.get(skill, [])

        if skill_resources:
            resources.append({
                "skill": skill,
                "resources": skill_resources
            })

    return resources