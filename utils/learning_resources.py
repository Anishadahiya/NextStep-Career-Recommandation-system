# GET LEARNING RESOURCES
# =========================================================

def get_learning_resources(missing_skills):

    recommendations = []

    if not missing_skills:
        return recommendations

    used_urls = set()

    for skill in missing_skills:

        original_skill = str(
            skill
        ).strip()

        if not original_skill:
            continue

        normalized_skill = (
            original_skill.lower()
        )

        # Exact match
        resource_key = normalized_skill

        # Alias match
        if resource_key not in LEARNING_RESOURCES:

            resource_key = SKILL_ALIASES.get(
                normalized_skill
            )

        # Nothing found
        if not resource_key:

            continue

        resources = LEARNING_RESOURCES.get(
            resource_key,
            []
        )

        selected_resources = []

        for resource in resources:

            url = resource.get(
                "url",
                ""
            )

            if not url:
                continue

            if url in used_urls:
                continue

            used_urls.add(url)

            selected_resources.append(
                resource
            )

        if selected_resources:

            recommendations.append(
                {
                    "skill": original_skill,
                    "resources": selected_resources
                }
            )

    return recommendations